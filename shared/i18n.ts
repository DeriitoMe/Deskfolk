/** App-owned copy only. Never translate project names or user/agent content. */
export type AppLocale = 'zh-CN' | 'en';
export type LanguagePreference = 'system' | AppLocale;
export const LANGUAGE_OPTIONS = ['system', 'zh-CN', 'en'] as const;

export function normalizeLanguage(value: unknown, fallback: LanguagePreference = 'system'): LanguagePreference {
  return LANGUAGE_OPTIONS.includes(value as LanguagePreference) ? value as LanguagePreference : fallback;
}

/** Chinese locales share Simplified Chinese for now; other locales use English. */
export function resolveLocale(language: unknown, systemLocale: string): AppLocale {
  const preference = normalizeLanguage(language);
  if (preference !== 'system') return preference;
  return /^zh(?:[-_]|$)/i.test(systemLocale) ? 'zh-CN' : 'en';
}

